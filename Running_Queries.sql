-- Getting all orders by a Users (Users and Vendors)
--Customer query
SELECT * FROM Users;
SELECT o.OrderID , o.OrderDate , o.TotalAmount , u.FullName
FROM Orders o JOIN Users u
ON o.UserID = u.UserID WHERE o.UserId =2;

--Vendors query
SELECT * FROM Vendors;
SELECT o.OrderID , o.TotalAmount , o.VendorID , v.VendorName
FROM Orders o JOIN Vendors v
ON o.UserID = v.VendorID WHERE o.VendorID=1;

--Ordres summary with items (Orders , OrdersItem Product)
SELECT * FROM Orders;
SELECT * FROM OrderItems;
SELECT * FROM Products;
SELECT  o.OrderID , p.Name , oi.Quantity , oi.Price
FROM Orders o JOIN OrderItems oi 
ON o.OrderID = oi.OrderID
JOIN Products p
ON p.ProductID = oi.ProductID;

-- Total Revenue generated by each vendor
SELECT * FROM Vendors;
SELECT * FROM Orders;
SELECT v.VendorName ,SUM(o.TotalAmount) AS "TotalRevenue"
FROM Orders o JOIN Vendors v
ON o.VendorID = v.VendorID
GROUP BY v.VendorName
ORDER BY "TotalRevenue" DESC;

