-- AVERAG PRODUCT RATING
SELECT * FROM Reviews;
SELECT * FROM Products;
SELECT p.Name , AVG(r.Rating) AS AvgRatings
FROM  Reviews r JOIN Products p
ON p.ProductID = r.ProductID
GROUP BY p.Name;

